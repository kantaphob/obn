function load(relative, mocks = {}, cache = false) {
  const file = path.resolve(root, relative);
  if (cache && modules.has(file)) return modules.get(file).exports;
  const source = fs.readFileSync(file, "utf8").replaceAll("import.meta.url", JSON.stringify(pathToFileURL(file).href));
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  if (cache) modules.set(file, mod);
  const require = createRequire(file);
  new Function("require", "module", "exports", code)((key) => {
    if (key in mocks) return mocks[key];
    if (key.startsWith(".")) return load(path.resolve(path.dirname(file), key.endsWith(".ts") ? key : `${key}.ts`), {}, true);
    return require(key);
  }, mod, mod.exports);
  return mod.exports;
}
